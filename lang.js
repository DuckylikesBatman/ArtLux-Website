  var curLang = 'en';

  function applyLang(lang) {
    if (!T[lang]) return;
    curLang = lang;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    localStorage.setItem('artlux-lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = T[lang][key];
      if (val === undefined) return;
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = val;
      } else {
        el.innerHTML = val;
      }
    });

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      var isActive = btn.getAttribute('data-lang') === lang;
      btn.classList.toggle('active', isActive);
      btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });

    document.dispatchEvent(new CustomEvent('artlux:langchange', { detail: { lang: lang } }));
  }

  /* Public API for pages with JS-driven content (e.g. the Projects modal)
     that need to look up a translation outside of a [data-i18n] element. */
  window.ArtLuxLang = {
    t: function (key) {
      var val = (T[curLang] && T[curLang][key] !== undefined) ? T[curLang][key] : T.en[key];
      return val === undefined ? key : val;
    },
    current: function () { return curLang; }
  };

  function init() {
    var saved = localStorage.getItem('artlux-lang');
    var lang = (saved && LANGS.indexOf(saved) !== -1) ? saved : 'en';
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.addEventListener('click', function () {
        applyLang(this.getAttribute('data-lang'));
      });
    });
    applyLang(lang);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
